namespace RSEV.Utilities.Processes
{
    /// <summary>
    /// Definiert die Log-Level für Prozess-Ausgaben.
    /// </summary>
    public enum ProcessLogLevel
    {
        /// <summary>
        /// Informationen (Info-Level).
        /// </summary>
        Info = 0,

        /// <summary>
        /// Warnungen (Warning-Level).
        /// </summary>
        Warning = 1,

        /// <summary>
        /// Fehler (Error-Level).
        /// </summary>
        Error = 2
    }
}
